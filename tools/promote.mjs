#!/usr/bin/env node
// Picks the version shown at "/" and writes the root copy of its site: index.html, talks/ and projects/<slug>/
// (from models/<id>/…, paths mapped back by tools/sitepaths.mjs).
//   - the registry's "pinned" id if set, otherwise
//   - the newest model = highest "order" (lineup position, CLAUDE.md §3) with status "ok".
// Ids starting with "_" are never promoted.
// If nothing qualifies, a placeholder page is written.
//
// Also validates every registered version: required head boilerplate, and no
// relative asset paths (they would break in the root copy).
//
// Usage: node tools/promote.mjs [--check]   (--check: validate only, write nothing)

import { readFileSync, writeFileSync, existsSync, rmSync, mkdirSync, cpSync } from "node:fs";
import { toRoot, eachFile } from "./sitepaths.mjs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const reg = JSON.parse(readFileSync(join(root, "content/models.json"), "utf8"));
const check = process.argv.includes("--check");
const models = reg.models || [];
let warnings = 0;
const warn = (m) => { warnings++; console.warn("warn:", m); };

const REQUIRED = [
  [/<meta\s+name="oz-model"\s+content="([^"]+)"/i, "meta oz-model"],
  [/<script\s+src="\/shared\/core\.js"\s*>/i, "core.js (not deferred)"],
  [/<script\s+src="\/shared\/topbar\.js"[^>]*>/i, "topbar.js"],
  [/<oz-topbar>/i, "<oz-topbar>"],
];

function validate(m) {
  const file = join(root, "models", m.id, "index.html");
  if (!existsSync(file)) { warn(`${m.id}: models/${m.id}/index.html not found (not released yet? tools/release.sh)`); return null; }
  const html = readFileSync(file, "utf8");
  for (const [re, label] of REQUIRED) if (!re.test(html)) warn(`${m.id}: missing ${label}`);
  const meta = html.match(REQUIRED[0][0]);
  if (meta && meta[1] !== m.id) warn(`${m.id}: oz-model meta says "${meta[1]}"`);
  const rel = [...html.matchAll(/\s(?:src|href)="(?!\/|https?:|#|mailto:|data:|tel:|javascript:)([^"]+)"/gi)].map((x) => x[1]);
  if (rel.length) warn(`${m.id}: relative paths break the root copy: ${[...new Set(rel)].slice(0, 5).join(", ")}`);
  return html;
}

const pages = Object.fromEntries(models.map((m) => [m.id, validate(m)]));

let pick = null;
if (reg.pinned) {
  pick = models.find((m) => m.id === reg.pinned) || null;
  if (!pick) warn(`pinned id "${reg.pinned}" not in registry`);
}
if (!pick) {
  pick = models
    .filter((m) => m.status === "ok" && !m.id.startsWith("_") && pages[m.id])
    .sort((a, b) => (b.order || 0) - (a.order || 0) || (b.builtOn || "").localeCompare(a.builtOn || ""))[0] || null;
}

let out;
if (pick && pages[pick.id]) {
  out = pages[pick.id]
    .replace(/<meta\s+name="oz-root"[^>]*>\s*/gi, "")
    .replace(/<meta\s+name="oz-model"[^>]*>/i, (m) =>
      `<!-- GENERATED by tools/promote.mjs from /models/${pick.id}/ — do not edit; release a different draft instead -->\n  ${m}\n  <meta name="oz-root" content="true">`);
} else {
  out = `<!doctype html>
<!-- GENERATED by tools/promote.mjs — placeholder until the first model version is registered -->
<html lang="tr"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>C. Murad Özsert</title>
<script src="/shared/core.js"></script><script src="/shared/topbar.js" defer></script>
<style>body{margin:0;font:18px/1.6 system-ui,sans-serif;background:#FBF8F1;color:#1A1714}[data-theme=dark] body{background:#16130F;color:#ECE7DE}
main{max-width:640px;margin:18vh auto 0;padding:0 16px}h1{font-size:clamp(36px,7vw,64px);line-height:1.05;letter-spacing:-.03em;margin:0 0 16px}</style>
</head><body><oz-topbar></oz-topbar><main><h1 data-i18n="hero.headline"></h1><p data-i18n="hero.role"></p>
<p><a href="/talks/" data-i18n="talks.all"></a> · <a href="/archive/v1/">v1</a></p></main></body></html>
`;
}

console.log(pick ? `promoted: ${pick.id} (${pick.name})` : "no eligible version — placeholder");
if (pick) out = toRoot(out, pick.id);
if (!check) writeFileSync(join(root, "index.html"), out);

// Root talks/ and projects/<slug>/: generated copies of the promoted model's pages (never edit them by hand).
if (pick && !check) {
  rmSync(join(root, "talks"), { recursive: true, force: true });
  rmSync(join(root, "projects"), { recursive: true, force: true });
  const from = join(root, "models", pick.id);
  for (const page of pick.pages || []) {
    if (page === "homepage") continue;
    const rel = page === "talks" ? "talks" : join("projects", page);
    if (!existsSync(join(from, rel, "index.html"))) { warn(`${pick.id}: ${rel}/ listed in "pages" but missing`); continue; }
    mkdirSync(join(root, rel), { recursive: true });
    cpSync(join(from, rel), join(root, rel), { recursive: true });
    eachFile(join(root, rel), (f) => writeFileSync(f, toRoot(readFileSync(f, "utf8"), pick.id)));
  }
  console.log(`root copy: / + ${(pick.pages || []).filter((x) => x !== "homepage").length} page(s) from /models/${pick.id}/`);
}
console.log(`${check ? "checked" : "wrote index.html"} — ${warnings} warnings`);
